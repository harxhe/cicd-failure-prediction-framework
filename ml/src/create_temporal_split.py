"""Create a leakage-safe chronological split for the Day 2 training CSV."""

import json
from pathlib import Path

import pandas as pd
from pandas.testing import assert_frame_equal

from feature_engineering import (
    TRAVIS_OUTPUT_COLUMNS,
    _normalize_travis_label,
    engineer_travistorrent,
    load_travistorrent,
)


ML_ROOT = Path(__file__).resolve().parents[1]
SOURCE_PATH = ML_ROOT / "data" / "travistorrent.csv.gz"
TRAINING_PATH = ML_ROOT / "data" / "training_features.csv"
SPLIT_DIR = ML_ROOT / "data" / "splits"
MANIFEST_PATH = SPLIT_DIR / "manifest.json"


def boundary_without_timestamp_split(sorted_source, target_index):
    """Move a split boundary forward so equal timestamps stay together."""
    if target_index <= 0 or target_index >= len(sorted_source):
        return target_index
    timestamp = sorted_source.iloc[target_index - 1]["timestamp"]
    while (
        target_index < len(sorted_source)
        and sorted_source.iloc[target_index]["timestamp"] == timestamp
    ):
        target_index += 1
    return target_index


def create_split():
    source = load_travistorrent(SOURCE_PATH)
    source["timestamp"] = pd.to_datetime(
        source["gh_build_started_at"], utc=True, errors="coerce"
    )
    source["label"] = source["tr_status"].map(_normalize_travis_label)
    source["repo"] = source["gh_project_name"]
    source = source.dropna(subset=["tr_build_id", "repo", "timestamp", "label"])
    source = source.sort_values(
        ["timestamp", "tr_build_id"], kind="mergesort"
    ).reset_index(drop=True)

    regenerated = engineer_travistorrent(source)
    existing = pd.read_csv(TRAINING_PATH, usecols=TRAVIS_OUTPUT_COLUMNS)
    if len(existing) != len(regenerated):
        raise ValueError(
            f"Row correspondence failed: existing={len(existing)}, "
            f"regenerated={len(regenerated)}"
        )
    assert_frame_equal(
        existing.reset_index(drop=True),
        regenerated.reset_index(drop=True),
        check_dtype=False,
        check_exact=False,
        rtol=1e-12,
        atol=1e-12,
    )

    total = len(existing)
    train_target = int(total * 0.70)
    validation_target = int(total * 0.85)
    train_end = boundary_without_timestamp_split(source, train_target)
    validation_end = boundary_without_timestamp_split(source, validation_target)
    if validation_end < train_end:
        raise ValueError("Chronological split boundaries are not monotonic")

    splits = {
        "train": existing.iloc[:train_end].copy(),
        "validation": existing.iloc[train_end:validation_end].copy(),
        "test": existing.iloc[validation_end:].copy(),
    }
    SPLIT_DIR.mkdir(parents=True, exist_ok=True)
    for name, frame in splits.items():
        frame.to_csv(SPLIT_DIR / f"{name}.csv", index=False)

    manifest = {
        "source_dataset": str(SOURCE_PATH),
        "source_feature_dataset": str(TRAINING_PATH),
        "split_method": "chronological; no random shuffling",
        "timestamp_order": "gh_build_started_at ascending, tr_build_id ascending tie-breaker",
        "same_timestamp_policy": "boundaries moved forward so equal timestamps stay together",
        "total_rows": total,
        "target_ratios": {"train": 0.70, "validation": 0.15, "test": 0.15},
        "actual_rows": {name: len(frame) for name, frame in splits.items()},
        "boundary_indices": {"train_end": train_end, "validation_end": validation_end},
        "feature_columns": TRAVIS_OUTPUT_COLUMNS[:-1],
        "label_column": "label",
        "historical_feature_rule": "Features were regenerated by the Day 2 pipeline using only strictly earlier builds.",
        "limitations": [
            "The split CSVs intentionally do not contain build_id, repo, or timestamp.",
            "Exact correspondence was verified by regenerating and comparing the existing training CSV.",
            "test_coverage_delta and author_recent_failure_rate remain unavailable and are not included.",
        ],
    }
    MANIFEST_PATH.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


if __name__ == "__main__":
    result = create_split()
    print(json.dumps(result, indent=2))